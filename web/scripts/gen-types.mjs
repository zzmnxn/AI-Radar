import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const schemaDir = new URL("../../schemas/", import.meta.url);
const declarations = new Map();

function typeOf(schema) {
  if (schema.$ref) {
    const name = schema.$ref.replace(/^#\/\$defs\//, "");
    if (!declarations.has(name)) throw new Error(`Unresolved schema reference ${schema.$ref}`);
    return name;
  }
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(" | ");

  switch (schema.type) {
    case "string":
    case "boolean":
    case "null":
      return schema.type;
    case "integer":
    case "number":
      return "number";
    case "array":
      return `Array<${typeOf(schema.items)}>`;
    case "object": {
      if (schema.additionalProperties && !schema.properties) {
        return `Record<string, ${typeOf(schema.additionalProperties)}>`;
      }
      const required = new Set(schema.required ?? []);
      const fields = Object.entries(schema.properties).map(
        ([name, property]) => `  ${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${typeOf(property)};`,
      );
      return `{\n${fields.join("\n")}\n}`;
    }
    default:
      throw new Error(`Unsupported Radar schema: ${JSON.stringify(schema)}`);
  }
}

function register(name, schema) {
  const previous = declarations.get(name);
  if (previous && JSON.stringify(previous) !== JSON.stringify(schema)) {
    throw new Error(`Conflicting definitions of ${name}`);
  }
  declarations.set(name, schema);
}

for (const filename of readdirSync(schemaDir).sort()) {
  if (!filename.endsWith(".schema.json")) continue;
  const { $defs = {}, ...schema } = JSON.parse(readFileSync(new URL(filename, schemaDir), "utf8"));
  for (const [name, definition] of Object.entries($defs)) register(name, definition);
  register(schema.title, schema);
}

const version = declarations.get("Manifest").properties.schema_version.const;
const types = [...declarations.entries()].sort(([a], [b]) => a.localeCompare(b, "en")).map(
  ([name, schema]) => `export type ${name} = ${typeOf(schema)};\n`,
);

writeFileSync(
  new URL("../src/lib/types.gen.ts", import.meta.url),
  [
    "// Generated by npm run gen:types.",
    `export const SCHEMA_VERSION = ${JSON.stringify(version)};\n`,
    ...types,
  ].join("\n"),
);
